/// What is wrong with a certificate. A bit set.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Default)]
pub struct CertStatus(pub u32);

impl CertStatus {
    /// No error.
    pub const NONE: CertStatus = CertStatus(0);
    /// Not issued by a trusted authority.
    pub const AUTHORITY_INVALID: CertStatus = CertStatus(1);
    /// Issued for another name.
    pub const NAME_INVALID: CertStatus = CertStatus(2);
    /// Expired or not yet valid.
    pub const DATE_INVALID: CertStatus = CertStatus(4);
    /// Revoked.
    pub const REVOKED: CertStatus = CertStatus(8);
    /// Weak signature or key.
    pub const WEAK: CertStatus = CertStatus(16);
    /// Invalid otherwise.
    pub const INVALID: CertStatus = CertStatus(32);
    /// Any other error.
    pub const OTHER: CertStatus = CertStatus(1 << 31);

    /// Whether every bit of `other` is set.
    pub fn contains(self, other: CertStatus) -> bool {
        self.0 & other.0 == other.0
    }

    /// Whether no bit is set.
    pub fn is_empty(self) -> bool {
        self.0 == 0
    }
}

impl std::ops::BitOr for CertStatus {
    type Output = CertStatus;
    fn bitor(self, rhs: CertStatus) -> CertStatus {
        CertStatus(self.0 | rhs.0)
    }
}

