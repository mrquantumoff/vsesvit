/// Why an engine call was refused.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum EngineError {
    /// Shutdown has begun: no new browsers (design section 3.6).
    ShuttingDown,
    /// No tab with this id.
    UnknownTab(TabId),
    /// The engine does not support the call.
    Unsupported,
    /// The engine failed.
    Failed(String),
}

impl std::fmt::Display for EngineError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            EngineError::ShuttingDown => f.write_str("the engine is shutting down"),
            EngineError::UnknownTab(tab) => write!(f, "no tab {}", tab.get()),
            EngineError::Unsupported => f.write_str("not supported by this engine"),
            EngineError::Failed(why) => write!(f, "engine failure: {why}"),
        }
    }
}

impl std::error::Error for EngineError {}
