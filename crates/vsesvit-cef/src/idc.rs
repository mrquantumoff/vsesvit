#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn chrome_ui_commands_are_refused() {
        for name in [
            "IDC_NEW_TAB",
            "IDC_NEW_WINDOW",
            "IDC_NEW_INCOGNITO_WINDOW",
            "IDC_CLOSE_TAB",
            "IDC_FULLSCREEN",
            "IDC_PRINT",
            "IDC_FIND",
            "IDC_DEV_TOOLS",
            "IDC_SHOW_HISTORY",
            "IDC_ZOOM_PLUS",
            "IDC_OPTIONS",
            "IDC_EXIT",
            "IDC_TASK_MANAGER_SHORTCUT",
            "IDC_PASTE_AND_GO",
            "IDC_VIEW_SOURCE",
            "IDC_SOMETHING_CEF_ADDS_LATER",
        ] {
            assert!(!allowed(name), "{name}");
        }
    }

    #[test]
    fn page_editing_and_menu_items_run() {
        for name in [
            "IDC_CONTENT_CONTEXT_COPY",
            "IDC_CONTENT_CONTEXT_INSPECTELEMENT",
            "IDC_SPELLCHECK_SUGGESTION_0",
            "IDC_COPY",
            "IDC_CUT",
            "IDC_PASTE",
            "IDC_STOP",
        ] {
            assert!(allowed(name), "{name}");
        }
    }

    #[test]
    fn the_table_maps_both_ways() {
        let id = id_of("IDC_NEW_TAB").expect("CEF knows IDC_NEW_TAB");
        assert_eq!(name_of(id), Some("IDC_NEW_TAB"));
        assert!(!admit(id));
        let copy = id_of("IDC_COPY").expect("CEF knows IDC_COPY");
        assert!(admit(copy));
    }

    #[test]
    fn an_issued_command_passes_once() {
        let console = id_of("IDC_DEV_TOOLS_CONSOLE").expect("CEF knows IDC_DEV_TOOLS_CONSOLE");
        assert!(!admit(console));
        issuing(console, || {
            assert!(admit(console));
            assert!(!admit(console), "once");
        });
        assert!(!admit(console));
    }
}
