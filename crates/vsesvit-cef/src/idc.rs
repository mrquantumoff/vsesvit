//! Owned by W1.3.
//! Chrome's command ids (`IDC_*`): the name table and the default-deny map (SC section 8.2). Chromium
//! dispatches its own accelerators and menu items as commands; in an embedded Chrome-style browser most
//! of them would open Chrome's native UI. `on_chrome_command` lets through only the allow list below and
//! a command the glue itself issued; everything else is refused, including every name CEF adds later.

use std::cell::Cell;
use std::collections::HashMap;
use std::sync::OnceLock;

/// The command's name, from CEF's own table (`cef_id_for_command_id_name`).
pub fn name_of(id: i32) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<i32, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| {
        IDC_NAMES
            .iter()
            .filter_map(|name| {
                // SAFETY: a NUL-terminated name from cef::resources.
                let id = unsafe { cef::sys::cef_id_for_command_id_name(name.as_ptr()) };
                Some((id, name.to_str().ok()?))
            })
            .filter(|(id, _)| *id >= 0)
            .collect()
    })
    .get(&id)
    .copied()
}

/// The command id for a name, or `None` if CEF does not know it.
pub fn id_of(name: &str) -> Option<i32> {
    let name = IDC_NAMES.iter().find(|n| n.to_str() == Ok(name))?;
    // SAFETY: a NUL-terminated name from cef::resources.
    let id = unsafe { cef::sys::cef_id_for_command_id_name(name.as_ptr()) };
    (id >= 0).then_some(id)
}

/// Whether a command Chromium dispatched on its own may run: page editing and the page's own context
/// menu items. Zoom is not among them: the shell intercepts it (Q10).
pub fn allowed(name: &str) -> bool {
    name.starts_with("IDC_CONTENT_CONTEXT_")
        || name.starts_with("IDC_SPELLCHECK_")
        || matches!(name, "IDC_CHECK_SPELLING_WHILE_TYPING" | "IDC_COPY" | "IDC_CUT" | "IDC_PASTE" | "IDC_STOP")
}

thread_local! {
    static ISSUED: Cell<Option<i32>> = const { Cell::new(None) };
}

/// Runs `f`, during which `command` (one the glue issues itself, `IDC_DEV_TOOLS_CONSOLE`) passes the
/// default-deny filter once. Main thread.
pub fn issuing<R>(command: i32, f: impl FnOnce() -> R) -> R {
    let before = ISSUED.replace(Some(command));
    let out = f();
    ISSUED.set(before);
    out
}

/// `on_chrome_command`'s decision: true lets Chromium run the command.
pub fn admit(id: i32) -> bool {
    if ISSUED.get() == Some(id) {
        ISSUED.set(None);
        return true;
    }
    name_of(id).is_some_and(allowed)
}

